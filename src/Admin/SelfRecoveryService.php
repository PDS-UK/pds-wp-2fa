<?php

declare(strict_types=1);

namespace PDS\WP2FA\Admin;

final class SelfRecoveryService
{
    public function __construct(private readonly RecoveryGenerationPort $generation)
    {
    }

    public function regenerate(AdminActor $actor): RecoveryGenerationResult
    {
        if ($actor->kind() !== 'user' || $actor->userId() === null) {
            throw new AdminException('Recovery codes can only be regenerated by the signed-in user.', 'authorization_denied');
        }

        return $this->generation->regenerateForUser($actor->userId());
    }
}
